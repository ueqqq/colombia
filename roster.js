// Fetches the live Towny/Dynmap marker feed, filters it down to this nation's
// towns and residents, and writes a small same-origin JSON file the website
// can read without hitting any CORS restrictions.
//
// The scheduled workflow uses scripts/sync_roster.py, which is covered by
// the parser tests. This Node version is an optional manual equivalent.

const fs = require('fs');
const path = require('path');

const DYNMAP_MARKERS_URL = 'https://map.diplomaticamc.com/tiles/minecraft_overworld/markers.json';
const NATION_FILTER = 'Cuba';
const OUTPUT_PATH = path.join(__dirname, 'roster.json');
const BUNDLE_PATH = path.join(__dirname, 'js', 'roster-data.js');

async function main() {
  const res = await fetch(DYNMAP_MARKERS_URL);
  if (!res.ok) {
    throw new Error(`Map feed responded with ${res.status} ${res.statusText}`);
  }
  const data = await res.json();

  const layers = data && Array.isArray(data.layers) ? data.layers : [];
  const claimsLayer = layers.find(l => l && l.id === 'towny_claims');
  if (!claimsLayer) {
    throw new Error('No "towny_claims" layer found in the map feed — has the map plugin changed?');
  }
  if (!Array.isArray(claimsLayer.markers)) {
    throw new Error('"towny_claims" markers are not a list.');
  }

  const townsByName = new Map();
  claimsLayer.markers.forEach(marker => {
    const meta = marker && marker.meta;
    if (!meta || meta['%nation%'] !== NATION_FILTER || !meta['%town%']) return;

    const name = String(meta['%town%']).replace(/_/g, ' ').trim();
    const mayor = String(meta['%mayor%'] || '').trim() || null;
    const residents = String(meta['%residents%'] || '')
      .split(',').map(username => username.trim()).filter(Boolean);
    const uniqueResidents = new Map();
    residents.forEach(username => {
      if (!uniqueResidents.has(username.toLowerCase())) {
        uniqueResidents.set(username.toLowerCase(), username);
      }
    });
    if (mayor) {
      uniqueResidents.delete(mayor.toLowerCase());
      uniqueResidents.set(mayor.toLowerCase(), mayor);
    }

    const key = name.toLowerCase();
    const town = townsByName.get(key) || { name, mayor, residents: [] };
    const knownResidents = new Set(town.residents.map(resident => resident.username.toLowerCase()));
    uniqueResidents.forEach(username => {
      if (!knownResidents.has(username.toLowerCase())) {
        town.residents.push({ username });
        knownResidents.add(username.toLowerCase());
      }
    });
    if (!town.mayor && mayor) town.mayor = mayor;
    townsByName.set(key, town);
  });

  const towns = Array.from(townsByName.values())
    .filter(town => town.name && town.residents.length)
    .sort((a, b) => a.name.localeCompare(b.name));

  if (!towns.length) {
    throw new Error(`No towns matched nation "${NATION_FILTER}" — check the filter or map data.`);
  }

  const output = {
    updatedAt: new Date().toISOString(),
    nation: NATION_FILTER,
    townCount: towns.length,
    residentCount: towns.reduce((sum, t) => sum + t.residents.length, 0),
    schemaVersion: 3,
    towns,
  };

  fs.writeFileSync(OUTPUT_PATH, JSON.stringify(output, null, 2) + '\n');
  fs.writeFileSync(
    BUNDLE_PATH,
    '// Generated by roster.js; do not edit by hand.\n' +
      'window.CUBA_ROSTER_DATA = ' + JSON.stringify(output, null, 2) + ';\n'
  );
  console.log(`Wrote ${towns.length} towns (${output.residentCount} residents) to ${OUTPUT_PATH}`);
  console.log(`Wrote browser-compatible roster bundle to ${BUNDLE_PATH}`);
}

main().catch(err => {
  console.error('Roster sync failed:', err.message);
  process.exit(1);
});
